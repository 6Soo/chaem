export type HolidayFn = (date: string) => boolean

export function makeHolidayFn(store: Pick<Store, 'holidayAdd' | 'holidayRemove'>): HolidayFn {
  const add = new Set(store.holidayAdd)
  const remove = new Set(store.holidayRemove)
  return (date) => !remove.has(date) && (add.has(date) || date in KR_HOLIDAYS)
}

export function holidayName(date: string, store: Pick<Store, 'holidayAdd' | 'holidayRemove'>): string | null {
  if (store.holidayRemove.includes(date)) return null
  if (date in KR_HOLIDAYS) return KR_HOLIDAYS[date]
  if (store.holidayAdd.includes(date)) return '휴일'
  return null
}
